-- 2. Quetes de donjon : experience x2 (l'XP vanilla est calculee depuis RewMoneyMaxLevel)
DROP TABLE IF EXISTS tmp_q1_dq;
CREATE TABLE tmp_q1_dq AS SELECT entry FROM quest_template
 WHERE ZoneOrSort IN (2437,1581,718,209,717,719,721,491,796,722,1337,1176,2100,1417,1584,1583,2557,2057,2017) OR Type=81;
UPDATE quest_template q JOIN bak_q1_quest_template b ON b.entry=q.entry SET q.RewMoneyMaxLevel=b.RewMoneyMaxLevel;
UPDATE quest_template q JOIN tmp_q1_dq d ON d.entry=q.entry JOIN bak_q1_quest_template b ON b.entry=q.entry
 SET q.RewMoneyMaxLevel=b.RewMoneyMaxLevel*2;

