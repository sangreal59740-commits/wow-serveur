-- 5. Boss de donjon : 2 objets rares (bleus) garantis, tires d'un lot adapte a leur niveau
DELETE FROM creature_loot_template WHERE item BETWEEN 990000 AND 990099 AND mincountOrRef<0;
DELETE FROM reference_loot_template WHERE entry BETWEEN 990000 AND 990099;
DROP TABLE IF EXISTS tmp_q1_drop;
CREATE TABLE tmp_q1_drop (item INT PRIMARY KEY);
INSERT IGNORE INTO tmp_q1_drop SELECT item FROM creature_loot_template WHERE mincountOrRef>0;
INSERT IGNORE INTO tmp_q1_drop SELECT item FROM reference_loot_template WHERE mincountOrRef>0;
DROP TABLE IF EXISTS tmp_q1_lv;
CREATE TABLE tmp_q1_lv (L INT PRIMARY KEY);
INSERT INTO tmp_q1_lv (L) SELECT DISTINCT MaxLevel FROM tmp_q1_boss;
INSERT INTO reference_loot_template (entry,item,ChanceOrQuestChance,groupid,mincountOrRef,maxcount,condition_id,comments)
 SELECT 990000+v.L, b.entry, 0, 1, 1, 1, 0, 'Custom : lot bleu boss de donjon'
 FROM tmp_q1_lv v JOIN bak_q1_item_template b
   ON b.ItemLevel BETWEEN GREATEST(v.L-2,20) AND GREATEST(v.L+5,26)
 JOIN tmp_q1_drop d ON d.item=b.entry
 WHERE b.Quality=3 AND b.class IN (2,4) AND b.InventoryType>0 AND b.requiredhonorrank=0
   AND b.RequiredReputationFaction=0 AND b.AllowableClass IN (-1,0,32767)
   AND b.name NOT LIKE '%Deprecated%' AND b.name NOT LIKE 'Monster%' AND b.name NOT LIKE '%Test%';
UPDATE creature_template c JOIN tmp_q1_boss b ON b.Entry=c.Entry SET c.LootId=c.Entry WHERE c.LootId=0;
INSERT IGNORE INTO creature_loot_template (entry,item,ChanceOrQuestChance,groupid,mincountOrRef,maxcount,condition_id,comments)
 SELECT c.LootId, 990000+b.MaxLevel, 100, 0, -(990000+b.MaxLevel), 2, 0, 'Custom : 2 bleus garantis'
 FROM tmp_q1_boss b JOIN creature_template c ON c.Entry=b.Entry
 WHERE EXISTS (SELECT 1 FROM reference_loot_template r WHERE r.entry=990000+b.MaxLevel);

